/* =========================================
   FINISH TURN
========================================= */

function finishTurn() {

    updateSafetyMessage();

    if (playerPosition >= TOTAL_CELLS) {

        finishGame();

        return;
    }

    rollButton.disabled = false;

    diceMessage.textContent =
        "Giliran seterusnya! Tekan DICE.";

    missionText.textContent =
        `Teruskan perjalanan ke petak 25. Sekarang kamu di petak ${playerPosition}.`;
}


/* =========================================
   FINISH GAME
========================================= */

function finishGame() {

    gameActive = false;

    rollButton.disabled = true;

    playerPosition =
        TOTAL_CELLS;

    updateAvatarPosition();

    finalScore.textContent =
        score;

    finalCoins.textContent =
        coins;

    boardMessage.innerHTML =
        "🏆 <strong>SCIENCE LAB TROPHY!</strong>";

    missionText.textContent =
        "Misi selesai! Kamu telah menjadi Junior Lab Scientist!";

    setTimeout(() => {

        winModal.classList.remove("hidden");

    }, 500);
}


